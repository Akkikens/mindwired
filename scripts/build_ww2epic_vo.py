def duration(p: Path) -> float:
    r = subprocess.run(["ffprobe", "-v", "error", "-show_entries", "format=duration",
        "-of", "default=noprint_wrappers=1:nokey=1", str(p)], capture_output=True, text=True)
    try: return float(r.stdout.strip())
    except ValueError: return 0.0


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--only", default="")
    ap.add_argument("--force", action="store_true")
    args = ap.parse_args()
    OUT.mkdir(parents=True, exist_ok=True)
    only = {s.strip() for s in args.only.split(",") if s.strip()}
    durs = []
    for bid, text in BEATS:
        if only and bid not in only: continue
        dst = OUT / f"{bid}.mp3"
        if dst.exists() and not args.force:
            print(f"skip {bid}")
        else:
            # Holocaust chapter (o*) reads slow + sombre throughout
            slow = bid.endswith("_t") or bid.startswith("o") or bid in {"h1", "h7", "h8", "b18"}
            audio = cartesia.tts(text, voice=ROHAN, language="hi", speed=0.92 if slow else 0.96)
            dst.write_bytes(audio); print(f"->  {bid}.mp3 ({len(audio)}b)")
        durs.append((bid, duration(dst)))
    print("\n--- durations ---")
    for bid, d in durs: print(f'  {{ id: "{bid}", aud: {d:.3f} }},')


if __name__ == "__main__":
    main()
